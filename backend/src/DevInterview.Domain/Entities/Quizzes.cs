using DevInterview.Domain.Common;
using DevInterview.Domain.Enums;

namespace DevInterview.Domain.Entities;

public class Quiz : ContentEntity
{
    public string Title { get; set; } = string.Empty;
    public string? Description { get; set; }
    public QuizMode Mode { get; set; }
    /// <summary>Null = untimed.</summary>
    public int? TimeLimitSeconds { get; set; }
    public int PassingPercentage { get; set; } = 60;
    /// <summary>Fraction of a question's points deducted for a wrong answer (0 = disabled, 0.25 = quarter).</summary>
    public decimal NegativeMarkingFraction { get; set; }
    public bool ShuffleQuestions { get; set; } = true;
    /// <summary>System quizzes are curated by admins; user quizzes are generated by "custom quiz".</summary>
    public bool IsSystem { get; set; }
    public Guid? OwnerUserId { get; set; }
    public bool IsPublished { get; set; }
    public bool IsPremium { get; set; }
    public Guid? TechnologyId { get; set; }
    public Technology? Technology { get; set; }
    public Guid? CategoryId { get; set; }
    public Difficulty? Difficulty { get; set; }
    /// <summary>For daily quizzes: the UTC date the quiz belongs to.</summary>
    public DateOnly? DailyDate { get; set; }
    public ICollection<QuizQuestion> Questions { get; set; } = new List<QuizQuestion>();
}

public class QuizQuestion : BaseEntity
{
    public Guid QuizId { get; set; }
    public Quiz Quiz { get; set; } = null!;
    public Guid QuestionId { get; set; }
    public Question Question { get; set; } = null!;
    public int DisplayOrder { get; set; }
    public decimal Points { get; set; } = 1m;
}

public class QuizAttempt : BaseEntity
{
    public Guid QuizId { get; set; }
    public Quiz Quiz { get; set; } = null!;
    public Guid UserId { get; set; }
    public QuizAttemptStatus Status { get; set; }
    public DateTime StartedAt { get; set; }
    /// <summary>Server-enforced deadline (StartedAt + time limit). Null for untimed quizzes.</summary>
    public DateTime? ExpiresAt { get; set; }
    public DateTime? SubmittedAt { get; set; }
    public decimal Score { get; set; }
    public decimal MaxScore { get; set; }
    public int TotalQuestions { get; set; }
    public int CorrectCount { get; set; }
    public int IncorrectCount { get; set; }
    public int SkippedCount { get; set; }
    public bool Passed { get; set; }
    /// <summary>JSON list of question ids in the order presented to this user.</summary>
    public string QuestionOrderJson { get; set; } = "[]";
    public ICollection<QuizAttemptAnswer> Answers { get; set; } = new List<QuizAttemptAnswer>();
}

public class QuizAttemptAnswer : BaseEntity
{
    public Guid AttemptId { get; set; }
    public QuizAttempt Attempt { get; set; } = null!;
    public Guid QuestionId { get; set; }
    public Question Question { get; set; } = null!;
    /// <summary>Comma-separated option ids.</summary>
    public string SelectedOptionIds { get; set; } = string.Empty;
    public bool IsMarkedForReview { get; set; }
    public bool? IsCorrect { get; set; }
    public decimal PointsAwarded { get; set; }
    public DateTime? AnsweredAt { get; set; }
    public int TimeSpentSeconds { get; set; }
}
